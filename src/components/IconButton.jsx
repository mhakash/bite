/**
 * Shared circular icon button. Icons are SVG (not text glyphs), so they
 * center reliably across browsers instead of drifting with font metrics.
 */
export default function IconButton({
  icon,
  size = 30,
  iconSize,
  variant = 'surface',
  className = '',
  style,
  ...props
}) {
  const svgSize = iconSize ?? Math.round(size * 0.45)

  return (
    <button
      type="button"
      className={`icon-button icon-button--${variant} ${className}`.trim()}
      style={{ width: size, height: size, ...style }}
      {...props}
    >
      <svg
        width={svgSize}
        height={svgSize}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2.4}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
      >
        {ICONS[icon]}
      </svg>
    </button>
  )
}
